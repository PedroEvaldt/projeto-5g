#!/usr/bin/env python3
"""
Packs the three source files into a Kubernetes ConfigMap.

The scripts are shipped as a ConfigMap instead of a container image on
purpose: no registry, no image build, and changing the code is a
`kubectl apply` plus a pod restart. The image can stay a plain
python:3.12-slim, since nothing here needs a pip install.

The generated YAML is derived, so do not edit it by hand. Regenerate it
after touching any of the .py files:

    python3 tools/gen-configmap.py --namespace 5gcore --out deploy/configmap.yaml

The three files land in the same directory inside the pod (/opt/photonpath
by default), which is what makes `import photon_clock` work: Python puts
the script's own directory on sys.path.
"""
import argparse
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")
SOURCES = ["photon_clock.py", "photon_server.py", "photon_client.py"]

HEADER = """# GENERATED by tools/gen-configmap.py. Do not edit by hand.
# Source: {sources}
# source checksum: {digest}
#
# PhotonPath scripts, mounted at {mount}:
#   photon_server.py  runs on the edge app and on the remote app
#   photon_client.py  runs on the UE side (inside the RAN simulator pod)
#   photon_clock.py   shared module: kernel timestamps and health counters
apiVersion: v1
kind: ConfigMap
metadata:
  name: {name}
  namespace: {ns}
  labels:
    app: {name}
data:
"""


def build(ns, name, mount):
    blobs = []
    digest = hashlib.sha256()
    for fname in SOURCES:
        with open(os.path.join(SRC, fname)) as fh:
            body = fh.read()
        digest.update(body.encode())
        indented = "\n".join(("    " + line) if line.strip() else ""
                             for line in body.rstrip("\n").split("\n"))
        blobs.append(f"  {fname}: |\n{indented}\n")
    head = HEADER.format(ns=ns, name=name, mount=mount,
                         sources=" ".join("src/" + f for f in SOURCES),
                         digest=digest.hexdigest()[:16])
    return head + "".join(blobs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--namespace", default="default")
    ap.add_argument("--name", default="photonpath",
                   help="ConfigMap name (default photonpath)")
    ap.add_argument("--mount", default="/opt/photonpath",
                   help="where the manifests mount it; only used in the "
                        "comment header")
    ap.add_argument("--out", default=os.path.join(HERE, "..", "deploy",
                                                  "configmap.yaml"))
    args = ap.parse_args()

    path = os.path.abspath(args.out)
    with open(path, "w") as fh:
        fh.write(build(args.namespace, args.name, args.mount))
    print(f"wrote {path} (namespace {args.namespace})")


if __name__ == "__main__":
    main()
